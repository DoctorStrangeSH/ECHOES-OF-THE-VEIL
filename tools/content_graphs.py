#!/usr/bin/env python3
"""Draw dialogue trees and case (quest) graphs as Mermaid diagrams.

  python3 tools/content_graphs.py            # writes docs/generated/dialogue.md and cases.md
  python3 tools/content_graphs.py --check    # fail if those files are out of date (CI)

GitHub renders the diagrams, so writers can review a branch without running the
game. Node labels show the English text, shortened; conditions show as edge labels.
"""
import glob, json, os, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
OUT = os.path.join(ROOT, 'docs', 'generated')
S = {}
for f in sorted(glob.glob(os.path.join(ROOT, 'data', 'localization', '*.json'))):
    S.update(json.load(open(f, encoding='utf-8')))


def text(key, n=48):
    t = S.get(key, {}).get('en', key) if key else ''
    t = t.replace('"', "'").replace('\n', ' ').replace('[', '(').replace(']', ')').replace('#', '')
    return t if len(t) <= n else t[:n - 1] + '…'


def cond(c):
    if not c:
        return ''
    s = json.dumps(c, ensure_ascii=False).replace('"', '')
    return s if len(s) <= 40 else s[:39] + '…'


def nid(*parts):
    return '_'.join(str(p) for p in parts).replace('.', '_').replace('-', '_')


def dialogue_md():
    out = ['# Dialogue graphs', '', 'Generated by `tools/content_graphs.py` — do not edit by hand.', '']
    for f in sorted(glob.glob(os.path.join(ROOT, 'data', 'dialogue', '*.json'))):
        data = json.load(open(f, encoding='utf-8'))
        out += [f'## {os.path.basename(f)}', '']
        for did, d in data.items():
            nodes = d.get('nodes', {})
            out += [f'### {did}', '', '```mermaid', 'flowchart TD']
            out.append(f'  {nid(did, "START")}(("start"))')
            if d.get('start'):
                out.append(f'  {nid(did, "START")} --> {nid(did, d["start"])}')
            for e in d.get('entries', []):
                out.append(f'  {nid(did, "START")} -->|"{cond(e.get("if"))}"| {nid(did, e["node"])}')
            for k, n in nodes.items():
                who = n.get('speaker', '')
                who = 'You' if who == 'player' else text(who, 20)
                label = (who + ': ' if who else '') + text(n.get('text'))
                out.append(f'  {nid(did, k)}["{k}<br/>{label}"]')
                if n.get('next'):
                    out.append(f'  {nid(did, k)} --> {nid(did, n["next"])}')
                for i, c in enumerate(n.get('choices', [])):
                    tgt = nid(did, c['next']) if c.get('next') else nid(did, k, 'end', i)
                    if not c.get('next'):
                        out.append(f'  {tgt}(["end"])')
                    lbl = text(c.get('text'), 30) + (' ⟨' + cond(c['if']) + '⟩' if c.get('if') else '')
                    out.append(f'  {nid(did, k)} -->|"{lbl}"| {tgt}')
            out += ['```', '']
    return '\n'.join(out) + '\n'


def cases_md():
    out = ['# Case graphs', '', 'Generated by `tools/content_graphs.py` — do not edit by hand.',
           'Solid arrows: declared stage transitions. Dotted: fail-forward help the game gives if the player is stuck.', '']
    for f in sorted(glob.glob(os.path.join(ROOT, 'data', 'journal', '*.json'))):
        data = json.load(open(f, encoding='utf-8'))
        for cid, c in data.get('cases', {}).items():
            out += [f'## {cid} — {text(c.get("title"), 60)}', '', '```mermaid', 'flowchart LR']
            for s, key in c.get('stages', {}).items():
                out.append(f'  {nid(cid, s)}["{s}<br/>{text(key, 40)}"]')
            for s, targets in c.get('transitions', {}).items():
                for t in targets:
                    out.append(f'  {nid(cid, s)} --> {nid(cid, t)}')
            for o, key in c.get('outcomes', {}).items():
                out.append(f'  {nid(cid, "out", o)}(["outcome: {o}<br/>{text(key, 30)}"])')
            if c.get('first_stage'):
                out.append(f'  {nid(cid, "START")}(("start")) --> {nid(cid, c["first_stage"])}')
            for i, ff in enumerate(c.get('fail_forward', [])):
                help_node = nid(cid, 'ff', i)
                out.append(f'  {help_node}{{{{"help: {text(ff.get("note"), 40)}"}}}}')
                out.append(f'  {nid(cid, ff.get("stage"))} -.->|"stuck {ff.get("after_days", "?")} days"| {help_node}')
                if ff.get('to'):
                    out.append(f'  {help_node} -.-> {nid(cid, ff["to"])}')
            out += ['```', '']
            ev = [e for e, v in data.get('evidence', {}).items() if v.get('advance', [None])[0] == cid]
            if ev:
                out += ['Evidence that advances this case: ' + ', '.join(f'`{e}`' for e in ev), '']
    return '\n'.join(out) + '\n'


def main():
    os.makedirs(OUT, exist_ok=True)
    files = {'dialogue.md': dialogue_md(), 'cases.md': cases_md()}
    if '--check' in sys.argv:
        stale = [n for n, t in files.items() if not os.path.exists(os.path.join(OUT, n)) or open(os.path.join(OUT, n), encoding='utf-8').read() != t]
        if stale:
            raise SystemExit('out of date: ' + ', '.join(stale) + ' (run python3 tools/content_graphs.py)')
        print('graphs up to date')
        return
    for n, t in files.items():
        open(os.path.join(OUT, n), 'w', encoding='utf-8').write(t)
    print('wrote ' + ', '.join('docs/generated/' + n for n in files))


if __name__ == '__main__':
    main()
