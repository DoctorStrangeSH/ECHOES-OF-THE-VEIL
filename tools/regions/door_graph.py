#!/usr/bin/env python3
"""Writes data/world/doors.json: for every region, its doors (node name,
target scene, show_if). The quest guide uses it at runtime to point at the
next door on the way to a quest's location. Run after editing regions;
tools/validate_content.py fails if the file is stale."""
import json, glob, os, sys

def build():
    out = {"_doc": "Generated by tools/regions/door_graph.py from data/regions. Do not edit."}
    for f in sorted(glob.glob('data/regions/*.json')):
        d = json.load(open(f))
        if 'nodes' not in d:
            continue
        rid = os.path.basename(f)[:-5]
        doors = []
        for n in d['nodes']:
            if n.get('kind') == 'door':
                e = {"node": n['name'], "to": n['scene']}
                if 'show_if' in n:
                    e['show_if'] = n['show_if']
                doors.append(e)
        out[rid] = doors
    return out

if __name__ == '__main__':
    text = json.dumps(build(), ensure_ascii=False, indent=1) + '\n'
    if '--check' in sys.argv:
        sys.exit(0 if os.path.exists('data/world/doors.json') and open('data/world/doors.json').read() == text else 1)
    open('data/world/doors.json', 'w').write(text)
