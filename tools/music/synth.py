"""A small offline synthesizer for the game's soundtrack (numpy + scipy).

Instruments are additive/FM/Karplus-Strong voices with envelopes; a Song
collects notes on tracks, then renders them with per-track gain/pan and a
shared convolution reverb. Renders loop seamlessly: whatever rings past the
end is folded back onto the start.

All music in assets/music is generated by tools/music/compose.py with this
module, so it is original and can live in the public repository.
"""
from __future__ import annotations

import numpy as np
from scipy.signal import fftconvolve, lfilter, butter

SR = 44100
A4 = 440.0
NOTE_INDEX = {"C": 0, "C#": 1, "Db": 1, "D": 2, "D#": 3, "Eb": 3, "E": 4, "F": 5, "F#": 6, "Gb": 6,
              "G": 7, "G#": 8, "Ab": 8, "A": 9, "A#": 10, "Bb": 10, "B": 11}


def midi(name: str) -> int:
    """'C4' -> 60, 'Bb3' -> 58."""
    i = 2 if len(name) > 2 and name[1] in "#b" else 1
    return 12 * (int(name[i:]) + 1) + NOTE_INDEX[name[:i]]


def freq(m: float) -> float:
    return A4 * 2 ** ((m - 69) / 12)


def _t(n: int) -> np.ndarray:
    return np.arange(n) / SR


def adsr(n: int, a: float, d: float, s: float, r: float, hold: float) -> np.ndarray:
    """Envelope of n samples: attack, decay to sustain s, hold until `hold` s, release."""
    t = _t(n)
    env = np.empty(n)
    a = max(a, 1e-4)
    env = np.where(t < a, t / a, 0.0)
    dec = (t >= a) & (t < a + d)
    env = np.where(dec, 1.0 - (1.0 - s) * (t - a) / max(d, 1e-4), env)
    env = np.where((t >= a + d) & (t < hold), s, env)
    level_at_hold = s if hold >= a + d else (1.0 - (1.0 - s) * max(0.0, hold - a) / max(d, 1e-4))
    rel = t >= hold
    env = np.where(rel, level_at_hold * np.exp(-(t - hold) / max(r, 1e-3) * 4.0), env)
    return env


def lowpass(x: np.ndarray, cutoff: float, order: int = 2) -> np.ndarray:
    b, a = butter(order, min(cutoff / (SR / 2), 0.99), btype="low")
    return lfilter(b, a, x)


def highpass(x: np.ndarray, cutoff: float, order: int = 2) -> np.ndarray:
    b, a = butter(order, min(cutoff / (SR / 2), 0.99), btype="high")
    return lfilter(b, a, x)


# --- Voices ------------------------------------------------------------------
# Each takes (frequency, duration in seconds, velocity 0..1, rng) and returns mono samples.

def piano(f, dur, vel, rng):
    tail = 1.8
    n = int((dur + tail) * SR)
    t = _t(n)
    out = np.zeros(n)
    B = 0.0004  # slight inharmonicity
    for k in range(1, 9):
        fk = f * k * np.sqrt(1 + B * k * k)
        if fk > SR / 2.2:
            break
        amp = (1.0 / k ** 1.3) * (0.6 + 0.4 * vel) ** (k * 0.3)
        decay = 0.9 + 2.2 * k * (f / 440) ** 0.5
        out += amp * np.sin(2 * np.pi * fk * t + rng.uniform(0, 6.28)) * np.exp(-t * decay * 0.6)
    # Body: long tone fades a little after release
    env = np.minimum(1.0, t / 0.004) * np.where(t < dur, 1.0, np.exp(-(t - dur) * 6.0))
    hammer = rng.normal(0, 1, n) * np.exp(-t * 300) * 0.05
    return (out * env + hammer) * vel * 0.32


def epiano(f, dur, vel, rng):
    """Rhodes-like FM tine."""
    tail = 1.2
    n = int((dur + tail) * SR)
    t = _t(n)
    index = (1.2 + 2.0 * vel) * np.exp(-t * 5.0)
    mod = np.sin(2 * np.pi * f * t) * index
    car = np.sin(2 * np.pi * f * t + mod) + 0.25 * np.sin(2 * np.pi * 2 * f * t) * np.exp(-t * 3)
    trem = 1.0 + 0.08 * np.sin(2 * np.pi * 4.2 * t)
    env = adsr(n, 0.003, 1.5, 0.35, 0.35, dur) * np.exp(-t * 0.6)
    return car * env * trem * vel * 0.3


def pad(f, dur, vel, rng):
    tail = 2.5
    n = int((dur + tail) * SR)
    t = _t(n)
    out = np.zeros(n)
    for det in (-0.07, 0.0, 0.06):
        fd = f * 2 ** (det / 12)
        ph = rng.uniform(0, 6.28)
        for k in range(1, 7):
            if fd * k > 6000:
                break
            out += (1.0 / k ** 1.6) * np.sin(2 * np.pi * fd * k * t + ph * k)
    out = lowpass(out, 1800 + 1200 * vel)
    env = adsr(n, 1.2, 0.8, 0.8, 1.6, dur)
    swell = 1.0 + 0.1 * np.sin(2 * np.pi * 0.23 * t + rng.uniform(0, 6))
    return out * env * swell * vel * 0.09


def bell(f, dur, vel, rng):
    tail = 3.0
    n = int((dur + tail) * SR)
    t = _t(n)
    out = np.zeros(n)
    for ratio, amp, dec in ((1.0, 1.0, 1.2), (2.76, 0.45, 2.5), (5.40, 0.25, 4.0), (8.93, 0.12, 6.0), (2.0, 0.3, 1.8)):
        if f * ratio < SR / 2.2:
            out += amp * np.sin(2 * np.pi * f * ratio * t) * np.exp(-t * dec)
    env = np.minimum(1.0, t / 0.002)
    return out * env * vel * 0.16


def musicbox(f, dur, vel, rng):
    n = int((dur + 2.0) * SR)
    t = _t(n)
    out = np.sin(2 * np.pi * f * t) * np.exp(-t * 2.4) + 0.35 * np.sin(2 * np.pi * f * 3.98 * t) * np.exp(-t * 6)
    out += 0.12 * np.sin(2 * np.pi * f * 6.9 * t) * np.exp(-t * 11)
    return out * np.minimum(1.0, t / 0.001) * vel * 0.22


def pluck(f, dur, vel, rng):
    """Karplus-Strong nylon-ish string."""
    n = int((dur + 1.4) * SR)
    period = SR / f
    N = int(period)
    frac = period - N
    burst = lowpass(rng.uniform(-1, 1, N + 2), 2500 + 3000 * vel)
    x = np.zeros(n)
    x[: N + 2] = burst
    decay = 0.996 - 0.002 * (f / 880)
    a = np.zeros(N + 3)
    a[0] = 1.0
    a[N] = -decay * (1 - frac) * 0.5
    a[N + 1] = -decay * 0.5
    a[N + 2] = -decay * frac * 0.5
    y = lfilter([1.0], a, x)
    t = _t(n)
    y *= np.where(t < dur + 0.05, 1.0, np.exp(-(t - dur - 0.05) * 8))
    return y * vel * 0.28


def bass(f, dur, vel, rng):
    n = int((dur + 0.4) * SR)
    t = _t(n)
    out = np.sin(2 * np.pi * f * t) + 0.25 * np.sin(2 * np.pi * 2 * f * t) + 0.08 * np.sin(2 * np.pi * 3 * f * t)
    env = adsr(n, 0.008, 0.25, 0.6, 0.12, dur)
    return np.tanh(out * 1.3) * env * vel * 0.32


def lead(f, dur, vel, rng):
    """Soft square-ish lead with vibrato (for combat/boss motifs)."""
    n = int((dur + 0.5) * SR)
    t = _t(n)
    vib = 1 + 0.004 * np.sin(2 * np.pi * 5.5 * t) * np.minimum(1, t / 0.4)
    ph = 2 * np.pi * f * np.cumsum(vib) / SR
    out = sum((1 / k) * np.sin(k * ph) for k in (1, 3, 5, 7))
    out = lowpass(out, 2600)
    env = adsr(n, 0.02, 0.2, 0.75, 0.2, dur)
    return out * env * vel * 0.16


def strings(f, dur, vel, rng):
    """Short bowed staccato / sustained ensemble."""
    n = int((dur + 0.8) * SR)
    t = _t(n)
    out = np.zeros(n)
    for det in (-0.05, 0.05, 0.0):
        fd = f * 2 ** (det / 12) * (1 + 0.003 * np.sin(2 * np.pi * 5 * t + rng.uniform(0, 6)))
        ph = 2 * np.pi * np.cumsum(fd) / SR
        out += sum((1 / k) * np.sin(k * ph) for k in range(1, 9))
    out = lowpass(out, 3000)
    env = adsr(n, 0.04, 0.3, 0.7, 0.3, dur)
    return out * env * vel * 0.06


# --- Drums ---------------------------------------------------------------------

def kick(vel, rng):
    n = int(0.45 * SR)
    t = _t(n)
    f = 45 + 90 * np.exp(-t * 30)
    ph = 2 * np.pi * np.cumsum(f) / SR
    return np.sin(ph) * np.exp(-t * 9) * vel * 0.8


def snare(vel, rng):
    n = int(0.3 * SR)
    t = _t(n)
    noise = highpass(rng.normal(0, 1, n), 1200) * np.exp(-t * 18)
    body = np.sin(2 * np.pi * 190 * t) * np.exp(-t * 25)
    return (noise * 0.35 + body * 0.4) * vel * 0.6


def brush(vel, rng):
    n = int(0.25 * SR)
    t = _t(n)
    return lowpass(highpass(rng.normal(0, 1, n), 2000), 7000) * np.exp(-t * 14) * vel * 0.12


def hat(vel, rng):
    n = int(0.08 * SR)
    t = _t(n)
    return lowpass(highpass(rng.normal(0, 1, n), 7000), 11000) * np.exp(-t * 60) * vel * 0.18


def shaker(vel, rng):
    n = int(0.12 * SR)
    t = _t(n)
    env = np.minimum(1, t / 0.02) * np.exp(-t * 35)
    return lowpass(highpass(rng.normal(0, 1, n), 4000), 9000) * env * vel * 0.1


def timpani(vel, rng):
    n = int(1.2 * SR)
    t = _t(n)
    f = 73.4 * (1 + 0.05 * np.exp(-t * 20))
    ph = 2 * np.pi * np.cumsum(f) / SR
    return (np.sin(ph) + 0.4 * np.sin(1.5 * ph)) * np.exp(-t * 3.5) * vel * 0.5


def accordion(f, dur, vel, rng):
    """Two slightly detuned reeds (musette), bellows swell."""
    tail = 0.15
    n = int((dur + tail) * SR)
    t = _t(n)
    out = np.zeros(n)
    for det in (-0.12, 0.12):
        fd = f * 2 ** (det / 12)
        ph = 2 * np.pi * fd * t + rng.uniform(0, 6.28)
        saw = np.zeros(n)
        for k in range(1, 12):
            if fd * k > 7000:
                break
            saw += ((-1) ** (k + 1)) * np.sin(k * ph) / k
        out += saw
    out = lowpass(out, 2600 + 1500 * vel)
    env = adsr(n, 0.04, 0.2, 0.85, 0.12, dur) * (1.0 + 0.06 * np.sin(2 * np.pi * 5.0 * t))
    return out * env * vel * 0.08


def organ(f, dur, vel, rng):
    """Drawbar flue pipes: 8', 4', 2 2/3', 2' with a slow chorus."""
    tail = 0.5
    n = int((dur + tail) * SR)
    t = _t(n)
    out = np.zeros(n)
    for ratio, amp in ((0.5, 0.5), (1.0, 1.0), (2.0, 0.55), (3.0, 0.25), (4.0, 0.2)):
        if f * ratio < SR / 2.2:
            out += amp * np.sin(2 * np.pi * f * ratio * t * (1 + 0.0007 * np.sin(2 * np.pi * 0.4 * t)))
    chiff = rng.normal(0, 1, n) * np.exp(-t * 60) * 0.08
    env = adsr(n, 0.06, 0.1, 0.95, 0.35, dur)
    return (out + chiff) * env * vel * 0.09


def flute(f, dur, vel, rng):
    """Breathy sine with a little second harmonic and delayed vibrato."""
    tail = 0.25
    n = int((dur + tail) * SR)
    t = _t(n)
    vib = 1 + 0.004 * np.sin(2 * np.pi * 5.2 * t) * np.minimum(1.0, t / 0.35)
    ph = 2 * np.pi * f * np.cumsum(vib) / SR
    out = np.sin(ph) + 0.18 * np.sin(2 * ph) + 0.05 * np.sin(3 * ph)
    breath = lowpass(rng.normal(0, 1, n), 3500) * 0.05
    env = adsr(n, 0.05, 0.1, 0.9, 0.18, dur)
    return (out + breath) * env * vel * 0.16


def choir(f, dur, vel, rng):
    """'Aah': several detuned voices through two vowel formants."""
    tail = 1.2
    n = int((dur + tail) * SR)
    t = _t(n)
    src = np.zeros(n)
    for det in (-0.1, -0.03, 0.04, 0.11):
        fd = f * 2 ** (det / 12)
        ph = 2 * np.pi * fd * t + rng.uniform(0, 6.28)
        vib = 0.003 * np.sin(2 * np.pi * rng.uniform(4.6, 5.6) * t)
        for k in range(1, 18):
            if fd * k > 5000:
                break
            src += np.sin(k * ph * (1 + vib)) / k
    from scipy.signal import butter, sosfilt
    out = np.zeros(n)
    for fc, bw, g in ((750, 180, 1.0), (1150, 220, 0.6), (2600, 300, 0.25)):
        sos = butter(2, [max(60, fc - bw) / (SR / 2), (fc + bw) / (SR / 2)], btype='band', output='sos')
        out += sosfilt(sos, src) * g
    env = adsr(n, 0.5, 0.4, 0.85, 1.0, dur)
    return out * env * vel * 0.12


VOICES = {"piano": piano, "epiano": epiano, "pad": pad, "bell": bell, "musicbox": musicbox,
          "pluck": pluck, "bass": bass, "lead": lead, "strings": strings,
          "accordion": accordion, "organ": organ, "flute": flute, "choir": choir}
DRUMS = {"kick": kick, "snare": snare, "brush": brush, "hat": hat, "shaker": shaker, "timpani": timpani}


# --- Song ----------------------------------------------------------------------

class Song:
    def __init__(self, bpm: float, bars: int, beats_per_bar: int = 4, seed: int = 1):
        self.bpm = bpm
        self.bars = bars
        self.bpb = beats_per_bar
        self.beat = 60.0 / bpm
        self.length = bars * beats_per_bar * self.beat
        self.rng = np.random.default_rng(seed)
        self.tracks: dict[str, dict] = {}

    def track(self, name: str, voice: str, gain: float = 1.0, pan: float = 0.0, reverb: float = 0.25):
        self.tracks[name] = {"voice": voice, "gain": gain, "pan": pan, "reverb": reverb, "events": []}
        return name

    def note(self, track: str, beat: float, pitch, dur_beats: float, vel: float = 0.8):
        """pitch: midi number or name like 'D4'."""
        m = midi(pitch) if isinstance(pitch, str) else pitch
        # Human feel: tiny timing and velocity variation.
        jitter = self.rng.normal(0, 0.006)
        v = float(np.clip(vel * (1 + self.rng.normal(0, 0.05)), 0.05, 1.0))
        self.tracks[track]["events"].append((beat * self.beat + jitter, m, dur_beats * self.beat, v))

    def hit(self, track: str, beat: float, vel: float = 0.8):
        jitter = self.rng.normal(0, 0.004)
        v = float(np.clip(vel * (1 + self.rng.normal(0, 0.08)), 0.05, 1.0))
        self.tracks[track]["events"].append((beat * self.beat + jitter, None, 0, v))

    def chord(self, track: str, beat: float, pitches, dur_beats: float, vel: float = 0.6, strum: float = 0.0):
        for i, p in enumerate(pitches):
            self.note(track, beat + i * strum, p, dur_beats, vel)

    def render(self, reverb_seconds: float = 2.6, master: float = 0.9) -> np.ndarray:
        L = int(self.length * SR)
        tail = int(6 * SR)
        dry = np.zeros((L + tail, 2))
        wet_send = np.zeros((L + tail, 2))
        for tr in self.tracks.values():
            buf = np.zeros(L + tail)
            voice = tr["voice"]
            for (start, m, dur, v) in tr["events"]:
                s = int(max(0.0, start) * SR)
                if voice in DRUMS:
                    x = DRUMS[voice](v, self.rng)
                else:
                    x = VOICES[voice](freq(m), dur, v, self.rng)
                e = min(len(buf), s + len(x))
                buf[s:e] += x[: e - s]
            p = (tr["pan"] + 1) / 2
            left, right = np.cos(p * np.pi / 2), np.sin(p * np.pi / 2)
            st = np.stack([buf * left, buf * right], axis=1) * tr["gain"] * 1.41
            dry += st
            wet_send += st * tr["reverb"]
        # Reverb: exponentially decaying stereo noise, gently low-passed.
        n_ir = int(reverb_seconds * SR)
        t = _t(n_ir)
        irs = []
        for ch in range(2):
            ir = self.rng.normal(0, 1, n_ir) * np.exp(-t * 6.9 / reverb_seconds)
            ir = lowpass(ir, 5000)
            ir[: int(0.012 * SR)] = 0
            irs.append(ir / np.sqrt(np.sum(ir ** 2)))
        wet = np.stack([fftconvolve(wet_send[:, ch], irs[ch])[: L + tail] for ch in range(2)], axis=1)
        mix = dry + wet * 0.9
        # Fold the tail back onto the start so the loop is seamless.
        out = mix[:L].copy()
        rest = mix[L:]
        while len(rest):
            k = min(L, len(rest))
            out[:k] += rest[:k]
            rest = rest[k:]
        # Gentle master: high-pass rumble, soft clip, normalise to an even loudness.
        out = np.stack([highpass(out[:, ch], 35) for ch in range(2)], axis=1)
        rms = np.sqrt(np.mean(out ** 2)) + 1e-9
        out *= 0.12 / rms
        out = np.tanh(out * 1.1) * master
        peak = np.max(np.abs(out))
        if peak > 0.97:
            out *= 0.97 / peak
        return out.astype(np.float32)
